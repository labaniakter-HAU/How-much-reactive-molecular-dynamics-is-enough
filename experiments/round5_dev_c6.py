# file: experiments/round5_dev_c6.py
"""Round 5 development for C6 (design section 16), HFO folds only (no MEA file is read): every campaign's flag
components, so that the cause of round 4's false alarms can be seen and revised rules can be scored.

  python -I -X utf8 experiments/round5_dev_c6.py            # components -> results/round5/dev_c6_hfo.json
Per campaign (C5's campaigns, regenerated by round4_lab.campaigns): the frozen C4 prediction and its sd per anchor,
the model's predicted flux at the target, the realized event-weighted RMS error, and the parts the frozen flag uses.
"""
import json
import sys
from multiprocessing import Pool
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "src"), str(ROOT / "experiments")]
import numpy as np  # noqa: E402
import torch  # noqa: E402

OUT = ROOT / "results" / "round5"


def fold(T_star):
    import round4_lab as r4
    import species
    torch.set_num_threads(1)
    T_of, data, S, O, groups, menu, A, pilot, train, test = r4.setup("HFO", T_star)
    camps = r4.campaigns("HFO", T_star, T_of, data, menu, A, pilot, test)
    g_test = species.batch(groups, test)
    obs, w = r4.observed(test, data, T_of, A)
    c0 = g_test.obs[0].numpy()
    out = []
    for name, camp in camps.items():
        runs = sorted(r for r, L in camp.items() if L)
        mean, sd, s2, tau2, lines = species.calibrated_re_k(camp, data, T_of, A, T_star)
        _, xi = species.predict(species.model(S, O, lines, A), g_test)
        f = xi.sum(0)
        err = np.minimum(np.abs(mean - obs), r4.CLIP)
        cmax = np.max([groups[r].obs.numpy().max((0, 1)) for r in runs], 0)
        dom = float(max(np.max(np.where(cmax[c0[b] > 0] > 0, c0[b][c0[b] > 0] / np.maximum(cmax[c0[b] > 0], 1e-300), np.inf))
                        for b in range(len(test))))
        out.append({"name": name, "runs": len(runs), "temps": len({T_of[r] for r in runs}),
                    "u_side": [float(min(1000 / T_of[r] for r in runs) - 1000 / T_star), float(max(1000 / T_of[r] for r in runs) - 1000 / T_star)],
                    "rms": float(np.sqrt((w * err ** 2).sum() / w.sum())), "s2": s2, "tau2": tau2, "dom": dom,
                    "sd": [float(x) for x in sd], "flux": [float(x) for x in f], "w": [float(x) for x in w],
                    "err": [float(x) for x in err], "seen": [int(x) for x in lines["seen"]], "m": [int(x) for x in lines["m"]]})
    return {"T": T_star, "campaigns": out}


def main():
    with Pool(5) as pool:
        res = pool.map(fold, [2500.0, 2750.0, 3000.0, 3250.0, 3500.0])
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "dev_c6_hfo.json").write_text(json.dumps(res))
    print(f"{sum(len(r['campaigns']) for r in res)} HFO campaigns -> results/round5/dev_c6_hfo.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
